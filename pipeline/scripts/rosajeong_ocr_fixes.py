HEADING = re.compile(r"^\s*(?:[가-힣]\.|\d\))")
NUMERIC_BEFORE = re.compile(r"[0-9억만원)]\s*$")


def _fix_dash(text):
    """`一`은 두 가지다 — 계산의 빼기와, 목차의 줄표 또는 논리 전개의 화살표.

    지면 대조 결과 목차 줄("가. 원상회복의 방법 一 목적물 양도")은 줄표(–),
    서술 줄("취소 가부 一 취소 범위 一 …")은 화살표(→)였다.
    """
    out = []
    for ln in text.split("\n"):
        if "一" not in ln:
            out.append(ln)
            continue
        if HEADING.match(ln):
            out.append(ln.replace("一", "–"))
            continue
        if ln.count("一") >= 3:                      # 화살표로 이어지는 논리 전개
            out.append(ln.replace("一", "→"))
            continue
        buf, last = [], 0
        for m in re.finditer("一", ln):
            buf.append(ln[last:m.start()])
            buf.append(" - " if NUMERIC_BEFORE.search(ln[:m.start()]) else "→")
            last = m.end()
        buf.append(ln[last:])
        out.append(re.sub(r" +", " ", "".join(buf)))
    return "\n".join(out)


def apply(text):
    # `으`가 C가 아닌 두 자리 — 먼저 처리해 아래 일괄 규칙에 걸리지 않게 한다
    text = text.replace("乙에게 배으가 인", "乙에게 배액인")
    text = text.replace("총 연체\n으가 이 2기분", "총 연체액이 2기분")
    for a, b in NUMBERS + MIXED + ERRATA + MISC:
        text = text.replace(a, b)
    for rx, b in CITE_RE + BRACKET_RE + MISC_RE + PARTY_RE:
        text = rx.sub(b, text)
    for a, b in PARTY.items():
        text = text.replace(a, b)
    # 당사자 기호 교정 뒤에야 드러나는 붙임 — 卜→F 로 바뀐 다음에 공백이 없는 게 보인다
    text = text.replace("저당권자F도", "저당권자 F도")
    return _fix_dash(text)
