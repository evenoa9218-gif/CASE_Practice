def load(prefix, name):
    idx = json.load(open(DATA / "index.json", encoding="utf-8"))
    lm = {i["id"]: i["label"] for i in idx["issues"]}
    out = {}
    for e in idx["exams"]:
        if not e["id"].startswith(prefix):
            continue
        no = e["label"].split(" · ")[0].replace(name + " ", "")
        out[no] = {
            "id": e["id"], "topic": e["topic"], "points": e["totalPoints"],
            "issues": [lm.get(i, i) for i in e["issueIds"][:3]],
        }
    return out


JUNK = re.compile(r"[^가-힣0-9\s()·\-—,.A-Za-z]")


def _safe(topic):
    """제목이 OCR로 깨져 있으면 링크 설명으로 쓰지 않는다."""
    return "사례 본문 참고" if JUNK.search(topic) else topic


def line(name, no, c, unit_topic):
    """단원 주제와 겹치는 쟁점은 빼고 적는다 — 그 단원에서는 정보가 없는 말이다."""
    url = SITE + "?exam=" + c["id"]   # 한글 그대로 — 브라우저가 알아서 인코딩한다
    drop = {re.sub(r"\s", "", unit_topic), re.sub(r"\s", "", c["topic"])}
    keep = [i for i in c["issues"] if re.sub(r"\s", "", i) not in drop]
    # 겹치는 걸 다 빼서 남는 게 없으면 겹쳐도 쟁점을 쓴다.
    # 사례 제목으로 되돌리면 OCR이 깨진 제목(`다^속과 동사사밍$`)이 그대로 노출된다.
    desc = "·".join(keep[:3]) or "·".join(c["issues"][:2]) or _safe(c["topic"])
    return f'- [**{name} {no}**]({url}) — {desc} <span color="gray">({c["points"]}점)</span>'


def unit_topics():
    """(과목, 번호) → 단원 주제. 쟁점 서술에서 겹치는 말을 빼는 데 쓴다."""
    return json.load(open(CASEBOOK / "romin_units.json", encoding="utf-8"))         if (CASEBOOK / "romin_units.json").exists() else {}


def blocks(topics=None):
    """단원 → CASE 섹션 마크다운. 두 책을 이어 붙이되 로사정을 먼저 놓는다."""
    topics = topics or {}
    loaded = [(name, load(prefix, name), m) for name, prefix, m in BOOKS]
    out = {}
    for key in sorted({k for _, _, m in loaded for k in m},
                      key=lambda k: (k[0], k[1])):
        ut = topics.get(f"{key[0]}|{key[1]}", "")
        lines = []
        for name, cases, m in loaded:
            seen = set()
            for no in m.get(key, []):
                no = str(no)
                if no in seen or no not in cases:
                    continue
                seen.add(no)
                lines.append(line(name, no, cases[no], ut))
        if lines:
            out[key] = "\n".join(lines)
    return out


