# -*- coding: utf-8 -*-
r"""박승수 「민법 기본사례」 본문(지문) 교정 — 1차.

`parkss_ocr_fixes.py`가 당사자 기호처럼 **전역으로 안전한** 치환을 맡는다면,
이 모듈은 **한 자리씩 지면과 대조해 확정한** 교정을 맡는다.

한글끼리의 오인식은 자동으로 못 찾는다. 두 가지로 후보를 좁혔다.
① **희귀 음절** — 본문 67만 자 중 3회 이하인 음절이 든 낱말 490종.
② **한 글자만 다른 흔한 낱말** — 4글자 이상, 이웃 빈도가 30배 이상일 때만.
   (2~3글자에 쓰면 `친한`→`대한` 같은 오탐이 쏟아진다. 한국어는 교착어라
   짧은 낱말은 한 글자 차이가 흔하다.)
그렇게 추린 지문 후보 211종을 줄 단위 대조표로 잘라 전부 눈으로 확인했다.
"""
import re

# ─────────────────────────────────────────────────────────────
# 사례 제목 띠에서 나온 줄은 전부 버린다. 무늬가 글자로 읽힌 것이든
# 제목 자체든 본문이 아니고, 제목은 `parkss_titles.py`에 따로 있어 잃는 것이 없다.
JUNK_RUN = re.compile(r"[SsBiIftM]{4,}")
# `사게 231 건물철거뫄 …★★★)법전엽` — 번호와 별점이 함께 있으면 제목 띠다.
BANNER = re.compile(r"^[사새시샤셔人ᄉ][^\d\s]{0,3}\s*\d{1,3}\s")
# 본문에 정상적으로 나오는 한자. 이것 말고 다른 한자가 여럿이면 무늬를 읽은 줄이다.
KNOWN_HANJA = set("甲乙丙丁戊己庚辛判例私見大法院全合條決有無人子母三十一二"
                  "前後上下中外內東西南北金水木火土")


def is_banner_noise(line):
    s = line.strip()
    if len(s) < 6:
        return False
    han = len(re.findall(r"[가-힣]", s))
    if BANNER.match(s) and ("★" in s or "大" in s or han / len(s) < 0.6):
        return True
    if JUNK_RUN.search(s) and han / len(s) < 0.25:
        return True
    odd = sum(1 for ch in s if "一" <= ch <= "鿿" and ch not in KNOWN_HANJA)
    return odd >= 3 and han / len(s) < 0.5


# ─────────────────────────────────────────────────────────────
# 앞뒤 글자까지 붙여 **그 자리에서만** 바뀌도록 한 것들.
ANCHORED = [
    ("논하시오.as다=53=", "논하시오.88다카4253·4260"),
    ("논하시오.쩌짜*", "논하시오.2007다17482"),
    ("논하시오J)", "논하시오.1)"),
    ("논하시오D", "논하시오1)"),
    ("매수하여r이", "매수하여 丁이"),
    ("계〒l행보", "계약이행보"),
    ("乙＜BCD는", "乙·B·C·D는"),
    ("ZX의 슬하", "乙과의 슬하"),
    ("오로부터 Y 건물", "B로부터 Y 건물"),
    ("0는 2024. 6. 19.", "C는 2024. 6. 19."),
    ("2. * 2018. 2. 15.", "2. 丙은 2018. 2. 15."),
    ("z과·의", "乙과의"),
    ("책% x게됨", "책임을 지게 됨"),
]

# 낱말째로 갈아도 안전한 것들 — 다른 낱말 속에 우연히 들어갈 수 없는 형태만 골랐다.
WORDS = [
    ("가객킌환의", "가액반환의"), ("시해행위", "사해행위"), ("밎", "및"),
    ("사해으k사", "사해의사"), ("적용도M", "적용되지"),
    ("손해배상첨구", "손해배상청구"), ("명의신틱", "명의신탁"),
    ("완닙하", "완납하"), ("긱하", "각하"), ("끽하", "각하"),
    ("딥하시오", "답하시오"), ("부동산게", "부동산에"),
    ("소액임X인", "소액임차인"), ("XI토지", "X1토지"),
    ("ZJ과의", "乙과의"), ("ZJ로부터", "乙로부터"), ("ZL과", "乙과"),
    ("인촣여계약임", "사인증여계약임"), ("뷔은", "甲은"),
    ("전제로 흐F고", "전제로 하고"),
    ("OD의", "C·D의"), ("OD를", "C·D를"),
]

# 당사자 기호가 소문자 로마자·다른 글자로 흘러버린 자리.
# 전부 지면에서 확인했다 — 이 책은 甲乙丙丁戊 말고 A~F도 함께 쓰기 때문에
# "소문자면 무조건 대문자"로 일반화하면 안 되고, 자리마다 확인해야 한다.
PARTY = [
    ("z에게", "乙에게"), ("z과 ", "乙과 "), ("z에 ", "乙에 "), ("o즈이", "乙이"),
    ("m에게", "丙에게"), ("m의 ", "丙과의 "),   # `丙과의`에서 `과`가 통째로 빠진 자리
    ("i차는", "丙는"), ("i치에게", "丙에게"), ("j차과", "丙과"), ("j차을", "丙을"),
    ("e가", "E가"), ("e에 ", "E에 "), ("e의 ", "E의 "),
    ("b가", "B가"), ("b는 ", "B는 "), ("a가", "A가"), ("a를", "A를"),
    ("c에게", "C에게"), ("c의 ", "C의 "),
    ("x건물에", "X건물에"), ("x토지를", "X토지를"),
]

# 책 지면에 그렇게 인쇄된 것 — OCR 잘못이 아니다.
# 같은 책 사례198은 `그 구체적인 범위를`로 제대로 적혀 있어 오기임이 확인된다.
ERRATA = [("전부인용시 구체적임 금액", "전부인용시 구체적인 금액")]


def apply(text):
    for a, b in ANCHORED + WORDS + PARTY + ERRATA:
        text = text.replace(a, b)
    return text
