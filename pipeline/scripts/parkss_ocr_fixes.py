r"""박승수 「민법 기본사례」(2025) OCR 오인식 교정표.

**전부 지면 이미지와 1:1 대조해 확정한 것만 넣는다.** 빈도나 문맥 추론으로 넣지 않는다 —
사례집에서 甲乙丙이 뒤바뀌면 답안이 통째로 무의미해진다.

당사자 기호는 원문에 **乙이 0회, 丙이 0회, 戊가 0회** 등장한다. 전부 오인식된 것이다.

| 원문 | OCR 결과 | 확인한 자리 |
|---|---|---|
| 乙 | 江 · 己 · 心 · 石 | p56 `甲·乙, 乙·丙` → `甲•江 己.R` / p110·p310 |
| 丙 | 內 · 因 · 西 · 雨 | p55 `甲·乙·丙 3자간` → `甲.2/西` |
| 戊 | 成 · J艾 | p48 경락인 · p110 |
| 계약 | 겨曾 | p18 `보증계약` → `보증겨曾` |

**`己`만은 일괄 치환하면 안 된다.** 이 책은 당사자가 여섯을 넘는 사례에서 진짜 `己`를 쓴다.
286개 사례 중 `丁`과 `戊`가 모두 나오는 30건을 골라 `己`가 든 207줄을 전부 지면과 대조한 결과,
**여섯 건만 진짜 `己`**였고 나머지는 전부 `乙`이었다. 그 여섯 건은 `GENUINE_GI`에 있다.
(#281은 `庚`까지 쓴다 — 텍스트층에 `庚`은 제대로 남아 있다.)
"""
import re

# 사례 단위로 적용한다 — 같은 글자가 사례마다 다른 뜻이라 전역 치환이 불가능하다.
GENUINE_GI = {22, 81, 204, 220, 250, 281}

PARTY = {"江": "乙", "心": "乙", "石": "乙",
         "內": "丙", "因": "丙", "西": "丙", "雨": "丙",
         "成": "戊"}
PARTY_GI = {"己": "乙"}          # GENUINE_GI 사례에서는 건드리지 않는다

# `戊`가 두 글자로 쪼개진 것. 앞의 J/丿/Ⲅ는 획이 떨어져 나온 것이다.
SPLIT_MU = re.compile(r"[JjＪ丿ﾉ/‚]\s*艾")

MISC = [
    ("겨曾", "계약"),          # 보증겨曾 · 매매겨曾 · 겨曾금
    ("겨自", "계약"),          # 같은 자리의 다른 오인식
    ("（", "("), ("）", ")"), ("：", ":"), ("，", ","),
    ("［", "["), ("］", "]"), ("•", "·"),
]

# 천단위 뒤에 공백이 낀다: `100, 000, 000`. 비중첩이라 안정될 때까지 돌린다.
NUM_GROUP = re.compile(r"(\d),\s+(\d{3})")


def apply(text, case_no=None):
    """`case_no`를 주면 그 사례의 `己` 처리까지 맞춘다. 안 주면 `己`는 그대로 둔다."""
    text = SPLIT_MU.sub("戊", text)
    for a, b in MISC:
        text = text.replace(a, b)
    for a, b in PARTY.items():
        text = text.replace(a, b)
    if case_no is not None and case_no not in GENUINE_GI:
        for a, b in PARTY_GI.items():
            text = text.replace(a, b)
    while True:
        new = NUM_GROUP.sub(r"\1,\2", text)
        if new == text:
            return new
        text = new
