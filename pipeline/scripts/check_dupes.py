def h(p: Path):
    return hashlib.md5(p.read_bytes()).hexdigest()


for subj, dt, names in GROUPS:
    d = BASE / subj / dt / "사례형" / "txt"
    print(f"=== [{subj}/{dt}] ===")
    info = []
    for n in names:
        p = d / n
        if not p.exists():
            print(f"  ✗ 없음: {n}")
            continue
        info.append((n, h(p), p.stat().st_size))
    hashes = {x[1] for x in info}
    if len(hashes) == 1 and len(info) > 1:
        print(f"  → 전부 동일 내용 ({len(info)}개). 하나만 남기고 삭제 가능")
        for n, _, sz in info:
            print(f"     {sz:>7,}B  {n}")
    else:
        print(f"  ⚠ 내용 다름 ({len(hashes)}종) — 수동 확인 필요")
        for n, hh, sz in info:
            print(f"     {sz:>7,}B  {hh[:8]}  {n}")
    print()
